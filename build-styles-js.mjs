// ============================================================
// NotionKit – Build Script: notionkit-styles.js
//
// Reads the minified CSS and embeds it into a JS module that
// exports ready-to-use CSSStyleSheet objects (Constructable
// Stylesheets) for use in Shadow DOM / Web Components.
//
// The CSS is additionally emitted split in two:
//
//   tokensCss      – the :root and [data-theme="dark"] blocks
//                    that declare --nk-*
//   componentsCss  – everything else
//
// Why: a shadow root that adopts the *whole* sheet re-declares
// every token on its own theme wrapper, and a matching rule always
// beats an inherited value. Document-level branding then cannot
// reach into the shadow root. Consumers that adopt only
// componentsCss keep inheritance intact and put tokensCss on the
// document instead. nkSheet/css stay unchanged for anyone already
// using them.
//
// Usage:  node build-styles-js.mjs
// ============================================================

import { readFileSync, writeFileSync } from 'fs';

const pkg = JSON.parse(readFileSync('package.json', 'utf-8'));
const css = readFileSync('notionkit.min.css', 'utf-8');

// ---- Split off the token blocks -------------------------------------------
// Both selectors appear exactly once in the minified output. The dark block is
// matched with its brace attached so that any `[data-theme=dark] .nk-*`
// component rule could not be mistaken for it.
const TOKEN_BLOCK_STARTS = [':root{', '[data-theme=dark]{'];

/** Returns [start, end) of the rule block beginning at `open`. */
function blockRange(source, open) {
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    if (source[i] === '{') depth++;
    else if (source[i] === '}') {
      depth--;
      if (depth === 0) return [open, i + 1];
    }
  }
  throw new Error('Unbalanced braces while splitting notionkit.min.css');
}

const ranges = TOKEN_BLOCK_STARTS.map(sel => {
  const at = css.indexOf(sel);
  if (at === -1) throw new Error(`Token block not found: ${sel}`);
  if (css.indexOf(sel, at + 1) !== -1) throw new Error(`Token block is not unique: ${sel}`);
  return blockRange(css, at);
});
ranges.sort((a, b) => a[0] - b[0]);

const tokensCss = ranges.map(([s, e]) => css.slice(s, e)).join('');
let componentsCss = '';
let cursor = 0;
for (const [s, e] of ranges) {
  componentsCss += css.slice(cursor, s);
  cursor = e;
}
componentsCss += css.slice(cursor);

// ---- Guard rails ----------------------------------------------------------
// A silently wrong split would ship components without styling, or tokens that
// cannot be branded, so fail the build instead.
const leakedToken = componentsCss.match(/--nk-[a-z0-9-]+\s*:/);
const checks = [
  [tokensCss.includes('--nk-accent:'), 'tokensCss is missing --nk-accent'],
  [tokensCss.includes('--nk-sidebar-width:'), 'tokensCss is missing --nk-sidebar-width'],
  [tokensCss.includes('color-scheme:light'), 'tokensCss lost the light color-scheme'],
  [tokensCss.includes('color-scheme:dark'), 'tokensCss lost the dark color-scheme'],
  [!leakedToken, `componentsCss still declares a token (${leakedToken?.[0]})`],
  [componentsCss.includes('.nk-btn'), 'componentsCss is missing component rules'],
  [componentsCss.includes('.nk-tree-item'), 'componentsCss lost the page-tree rules'],
  [componentsCss.includes('::slotted('), 'componentsCss lost the ::slotted() twins'],
  [tokensCss.length + componentsCss.length === css.length, 'split lost or duplicated bytes'],
];
for (const [ok, message] of checks) {
  if (!ok) throw new Error(`Split check failed: ${message}`);
}

// The two token blocks sit next to each other, so the full sheet is exactly
// head + tokens + tail. Emitting the parts and re-joining them at runtime keeps
// the module from carrying the CSS twice.
const head = css.slice(0, ranges[0][0]);
const tail = css.slice(ranges[ranges.length - 1][1]);
if (head + tokensCss + tail !== css) {
  throw new Error('Token blocks are not contiguous – cannot reconstruct css');
}

const output = [
  `// NotionKit v${pkg.version} – Constructable Stylesheet`,
  '// Auto-generated by build-styles-js.mjs – do not edit manually.',
  '',
  '// The :root and [data-theme="dark"] blocks that declare --nk-* …',
  `const tokensCss = ${JSON.stringify(tokensCss)};`,
  '',
  '// … and everything else, in two pieces around where they were.',
  `const componentsHead = ${JSON.stringify(head)};`,
  `const componentsTail = ${JSON.stringify(tail)};`,
  '',
  'const componentsCss = componentsHead + componentsTail;',
  'const css = componentsHead + tokensCss + componentsTail;',
  '',
  'const nkSheet = new CSSStyleSheet();',
  'nkSheet.replaceSync(css);',
  '',
  'const tokensSheet = new CSSStyleSheet();',
  'tokensSheet.replaceSync(tokensCss);',
  '',
  'const componentsSheet = new CSSStyleSheet();',
  'componentsSheet.replaceSync(componentsCss);',
  '',
  'export { nkSheet, css, tokensSheet, tokensCss, componentsSheet, componentsCss };',
  '',
].join('\n');

writeFileSync('notionkit-styles.js', output);

const kb = n => (Buffer.byteLength(n) / 1024).toFixed(1);
console.log(
  `✅ notionkit-styles.js generated (v${pkg.version}, ${kb(output)} KB` +
  ` – tokens ${kb(tokensCss)} KB, components ${kb(componentsCss)} KB)`
);
